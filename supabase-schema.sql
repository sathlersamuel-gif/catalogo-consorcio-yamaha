create extension if not exists pgcrypto;
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists private.catalog_admin_emails (
  email text primary key check (email = lower(trim(email)) and position('@' in email) > 1),
  created_at timestamptz not null default now()
);

revoke all on private.catalog_admin_emails from public, anon, authenticated;
grant usage on schema private to authenticated;
grant select on private.catalog_admin_emails to authenticated;
alter table private.catalog_admin_emails enable row level security;
drop policy if exists "Admin checks own catalog access" on private.catalog_admin_emails;
create policy "Admin checks own catalog access" on private.catalog_admin_emails
for select to authenticated
using (
  email = lower((select auth.jwt()->>'email'))
  and coalesce((select (auth.jwt()->>'is_anonymous')::boolean), false) is false
);

create or replace function private.is_catalog_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select
    coalesce((select (auth.jwt()->>'is_anonymous')::boolean), false) is false
    and exists (
      select 1
      from private.catalog_admin_emails admins
      where admins.email = lower((select auth.jwt()->>'email'))
    );
$$;

revoke all on function private.is_catalog_admin() from public, anon;
grant execute on function private.is_catalog_admin() to authenticated;

