drop policy if exists "Public creates leads" on public.leads;
create policy "Public creates leads" on public.leads for insert to anon with check (
  exists (
    select 1
    from public.plans p
    join public.motos m on m.id = p.moto_id
    join public.categories c on c.id = m.category_id
    where p.id = leads.plan_id
      and m.id = leads.moto_id
      and m.name = leads.moto_name
      and p.installments = leads.installments
      and p.installment_value = leads.installment_value
      and p.active and m.active and c.active
  )
);
drop policy if exists "Admin reads leads" on public.leads;
create policy "Admin reads leads" on public.leads for select to authenticated using ((select private.is_catalog_admin()));
drop policy if exists "Admin deletes leads" on public.leads;
create policy "Admin deletes leads" on public.leads for delete to authenticated using ((select private.is_catalog_admin()));

