create or replace function public.replace_moto_plans(p_moto_id text, p_plans jsonb)
returns setof public.plans
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  if not (select private.is_catalog_admin()) then
    raise exception 'Acesso não autorizado';
  end if;
  if not exists (select 1 from public.motos where id = p_moto_id) then
    raise exception 'Moto não encontrada';
  end if;
  if jsonb_typeof(p_plans) <> 'array' or jsonb_array_length(p_plans) = 0 then
    raise exception 'Cadastre pelo menos um plano';
  end if;

  delete from public.plans where moto_id = p_moto_id;
  insert into public.plans (moto_id, installments, installment_value, label, active, sort_order)
  select
    p_moto_id,
    (item->>'installments')::integer,
    (item->>'installment_value')::numeric,
    coalesce(item->>'label', ''),
    coalesce((item->>'active')::boolean, true),
    coalesce((item->>'sort_order')::integer, ordinality::integer)
  from jsonb_array_elements(p_plans) with ordinality as rows(item, ordinality);

  return query select p.* from public.plans p where p.moto_id = p_moto_id order by p.sort_order, p.installments;
end;
$$;

revoke all on function public.replace_moto_plans(text, jsonb) from public, anon;
grant execute on function public.replace_moto_plans(text, jsonb) to authenticated;

create or replace function public.set_updated_at()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

